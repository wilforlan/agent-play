function normalizeWord(raw) {
  const s = String(raw).trim().toLowerCase();
  if (s.length < 2 || s.length > 32) {
    return null;
  }
  if (!/^[a-z]+(?:-[a-z]+)*$/.test(s)) {
    return null;
  }
  return s;
}

function uniqueSorted(arr) {
  return [...new Set(arr)].sort((a, b) => a.localeCompare(b));
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`fetch ${url}: ${res.status}`);
  }
  return res.json();
}

async function main() {
  const buckets = {
    nouns: [],
    verbs: [],
    adjectives: [],
    adverbs: [],
  };

  for (const src of SOURCES) {
    const json = await fetchJson(src.url);
    const raw = src.extract(json);
    if (!Array.isArray(raw)) {
      throw new Error(`extract() did not return array for ${src.url}`);
    }
    for (const w of raw) {
      const n = normalizeWord(w);
      if (n !== null) {
        buckets[src.bucket].push(n);
      }
    }
  }

  buckets.nouns = uniqueSorted(buckets.nouns);
  buckets.verbs = uniqueSorted(buckets.verbs);
  buckets.adjectives = uniqueSorted(buckets.adjectives);
  buckets.adverbs = uniqueSorted(buckets.adverbs);

  const total =
    buckets.nouns.length +
    buckets.verbs.length +
    buckets.adjectives.length +
    buckets.adverbs.length;

  if (total < 15000) {
    throw new Error(
      `expected at least 15000 words after normalization, got ${total}`
    );
  }
  if (buckets.verbs.length < 2000) {
    throw new Error(
      `expected at least 2000 verb morphemes after normalization, got ${buckets.verbs.length}`
    );
  }

  const header = `/**
 * Auto-generated by scripts/build-passphrase-wordlist.mjs — do not edit by hand.
 * Word sources: dariusk/corpora (CC0), https://github.com/dariusk/corpora
 * Files: nouns, personal_nouns, compounds, strange_words, units_of_time, rhymeless_words, verbs, infinitive_verbs, state_verbs, ergative_verbs, resume_action_words, verbs_with_conjugations, adjs, encouraging_words, adverbs
 * Normalization: lowercase, a-z and hyphenated tokens only, length 2–32, nested forms flattened, deduplicated per bucket.
 * Total: ${total}
 */
`;

  const body = `export const passphraseNouns = ${JSON.stringify(buckets.nouns)} as const;

export const passphraseVerbs = ${JSON.stringify(buckets.verbs)} as const;

export const passphraseAdjectives = ${JSON.stringify(buckets.adjectives)} as const;

export const passphraseAdverbs = ${JSON.stringify(buckets.adverbs)} as const;

export const passphraseWordlistTotalCount = ${total} as const;
`;

  for (const outPath of outPaths) {
    writeFileSync(outPath, header + body, "utf8");
  }
  console.log(
    `Wrote ${outPaths.length} files: nouns=${buckets.nouns.length} verbs=${buckets.verbs.length} adjectives=${buckets.adjectives.length} adverbs=${buckets.adverbs.length} total=${total}`
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
